import { useMutation, useQuery } from '@tanstack/react-query';
import { Download, ShieldAlert, ShieldCheck } from 'lucide-react';
import { Link, useParams } from 'react-router';
import { Badge, Button, Card, ErrorNote, Hash, PageHeader, Spinner, StatusBadge } from '../components/ui';
import { api, post } from '../lib/api';
import { eventLabel, formatMoney } from '../lib/format';
import { useSession } from '../lib/session';
import type { SignedReceipt } from '../lib/types';

export function ReceiptPage() {
  const { id } = useParams();
  const { users } = useSession();
  const names = Object.fromEntries(users.map((u) => [u.id, u.name]));
  const q = useQuery({ queryKey: ['receipt', id], queryFn: () => api<SignedReceipt>(`/artifacts/${id}/receipt`) });
  const verify = useMutation({
    mutationFn: (r: SignedReceipt) => post<{ valid: boolean }>('/receipts/verify', { document: r.document, signature: r.signature, publicKeyPem: r.publicKeyPem }),
  });

  if (q.isLoading) return <Spinner />;
  if (q.error) return <ErrorNote error={q.error} />;
  const r = q.data!;
  const d = r.document;

  const download = () => {
    const blob = new Blob([JSON.stringify(r, null, 2)], { type: 'application/json' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = `tracepay-receipt-${d.artifact.id}.json`;
    a.click();
    URL.revokeObjectURL(a.href);
  };

  return (
    <>
      <PageHeader
        title="Audit Receipt"
        subtitle={<>One signed record connecting <strong>{d.artifact.title}</strong> to its sources, rights check, PayPal sale, settlement and payouts.</>}
        action={
          <div className="flex gap-2">
            <Button variant="secondary" onClick={download}>
              <Download className="size-4" /> Download JSON
            </Button>
            <Button loading={verify.isPending} onClick={() => verify.mutate(r)}>
              <ShieldCheck className="size-4" /> Verify signature
            </Button>
          </div>
        }
      />

      {verify.data && (
        <div className={`mb-6 flex items-center gap-2 rounded-lg px-4 py-3 text-sm font-medium ${verify.data.valid ? 'bg-verified-soft text-verified' : 'bg-block-soft text-block'}`}>
          {verify.data.valid ? <ShieldCheck className="size-4" /> : <ShieldAlert className="size-4" />}
          {verify.data.valid ? 'Valid Ed25519 signature: this receipt has not been modified since it was issued.' : 'Signature INVALID: the receipt was modified.'}
        </div>
      )}

      <div className="grid gap-6 lg:grid-cols-2">
        <Card title="1 · Artifact">
          <dl className="grid grid-cols-[8rem_1fr] gap-y-1.5 text-sm">
            <dt className="text-muted">Artifact</dt><dd><Hash value={d.artifact.id} n={24} /></dd>
            <dt className="text-muted">Content hash</dt><dd><Hash value={d.artifact.contentHash} n={24} /></dd>
            <dt className="text-muted">Generated by</dt><dd>{d.artifact.fromFixture ? <Badge tone="warn">fixture writer</Badge> : d.artifact.model}</dd>
            <dt className="text-muted">Price</dt><dd>{formatMoney(d.artifact.priceCents)}</dd>
            <dt className="text-muted">Credits</dt><dd>{d.artifact.credits.join('; ') || '—'}</dd>
          </dl>
        </Card>

        <Card title="2 · Rights check">
          <dl className="grid grid-cols-[8rem_1fr] gap-y-1.5 text-sm">
            <dt className="text-muted">Verdict</dt><dd><StatusBadge status={d.rights.preflight.verdict} /></dd>
            <dt className="text-muted">Policy</dt><dd className="mono">{d.rights.preflight.policyVersion}</dd>
            <dt className="text-muted">Evaluated on</dt><dd>{d.rights.asOf}</dd>
            <dt className="text-muted">Rules evaluated</dt><dd>{d.rights.preflight.rulesEvaluated}</dd>
            <dt className="text-muted">Terms snapshot</dt><dd><Hash value={d.rights.snapshotHash} n={24} /></dd>
          </dl>
        </Card>

        <Card title="3 · Licensed sources" className="lg:col-span-2">
          <table className="w-full text-sm">
            <thead className="text-left text-xs text-muted">
              <tr><th className="pb-2 font-medium">Source</th><th className="pb-2 font-medium">Owner</th><th className="pb-2 font-medium">License</th><th className="pb-2 font-medium">SHA-256</th><th className="pb-2 font-medium">Cited</th></tr>
            </thead>
            <tbody className="divide-y divide-line">
              {d.sources.map((s) => (
                <tr key={s.assetVersionId}>
                  <td className="py-2 font-medium">{s.title} <span className="text-xs text-muted">v{s.version}</span></td>
                  <td className="py-2">{s.owner}</td>
                  <td className="py-2 mono">{s.licenseId}</td>
                  <td className="py-2"><Hash value={s.sha256} /></td>
                  <td className="py-2">{s.cited ? <Badge tone="pass">yes</Badge> : <Badge>no</Badge>}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </Card>

        <Card title="4 · Sales, settlement and payouts" className="lg:col-span-2">
          {d.sales.length === 0 ? (
            <p className="text-sm text-muted">No verified sales yet.</p>
          ) : (
            <div className="space-y-6">
              {d.sales.map((s) => (
                <div key={s.saleId} className="space-y-3">
                  <div className="flex flex-wrap items-center gap-3 text-sm">
                    <StatusBadge status={s.status} />
                    <span>PayPal order <Hash value={s.paypal.orderId} n={18} /></span>
                    <span>capture <Hash value={s.paypal.captureId} n={18} /></span>
                    <span className="font-medium">{formatMoney(s.paypal.capturedCents)} {s.paypal.captureStatus}</span>
                  </div>
                  {s.settlement && (
                    <table className="w-full text-sm">
                      <thead className="text-left text-xs text-muted">
                        <tr><th className="pb-1 font-medium">Recipient</th><th className="pb-1 font-medium">Calculation</th><th className="pb-1 text-right font-medium">Amount</th><th className="pb-1 pl-4 font-medium">Payout</th></tr>
                      </thead>
                      <tbody className="divide-y divide-line">
                        {s.settlement.lines.map((l, i) => (
                          <tr key={i}>
                            <td className="py-1.5">{names[l.recipientId] ?? l.recipientId}</td>
                            <td className="py-1.5 mono">{l.formula}</td>
                            <td className="py-1.5 text-right tabular-nums">{formatMoney(l.amountCents)}</td>
                            <td className="py-1.5 pl-4">{l.payout ? <StatusBadge status={l.payout.status} /> : <span className="text-muted">{l.kind === 'publisher_residual' ? 'retained' : '—'}</span>}</td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  )}
                </div>
              ))}
            </div>
          )}
        </Card>

        <Card title="5 · Audit trail" className="lg:col-span-2" action={<Badge tone={d.chain.verified ? 'pass' : 'block'}>{d.chain.verified ? 'Hash chain verified' : 'Hash chain broken'}</Badge>}>
          <ol className="divide-y divide-line text-sm">
            {d.auditTrail.map((e) => (
              <li key={e.seq} className="flex items-center justify-between gap-3 py-1.5">
                <span><span className="mono mr-2 text-muted">#{e.seq}</span><span className="capitalize">{eventLabel(e.eventType)}</span></span>
                <Hash value={e.hash} n={12} />
              </li>
            ))}
          </ol>
        </Card>

        <Card title="Signature" className="lg:col-span-2">
          <dl className="grid grid-cols-[8rem_1fr] gap-y-2 text-sm">
            <dt className="text-muted">Algorithm</dt><dd>{r.algorithm}</dd>
            <dt className="text-muted">Signature</dt><dd className="mono break-all">{r.signature}</dd>
            <dt className="text-muted">Public key</dt><dd><pre className="mono whitespace-pre-wrap text-slate-700">{r.publicKeyPem}</pre></dd>
          </dl>
          <p className="mt-3 text-xs text-muted">{d.disclaimer}</p>
          <Link to={`/reports/${d.artifact.id}/provenance`} className="mt-3 inline-block text-sm font-medium text-brand hover:underline">Open the provenance graph →</Link>
        </Card>
      </div>
    </>
  );
}
